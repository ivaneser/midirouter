def fm(fc, fm_, index, t):
    return np.sin(2 * np.pi * fc * t + index * np.sin(2 * np.pi * fm_ * t))


def spectrum(sig, fmax, n=SR):
    s = np.abs(np.fft.rfft(sig[:n] * np.hanning(n))) / n * 4
    f = np.fft.rfftfreq(n, 1 / SR)
    m = f <= fmax
    return f[m], s[m]


